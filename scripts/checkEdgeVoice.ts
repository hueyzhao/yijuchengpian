import { strict as assert } from "node:assert";
import { boundaryCues, requireEdge } from "../src/edgeVoice";
import { validateStory } from "../src/story";
const text = "天黑了，小蜗牛回家。";
const words = [{ text: "天黑了", start: .1, end: 1 }, { text: "小蜗牛", start: 1.4, end: 2 }, { text: "回家", start: 2.1, end: 3 }];
const cues = boundaryCues(text, words);
assert.equal(cues.map(c => c.text).join(""), text);
assert.deepEqual(cues, [{ text: "天黑了，", start: .1, end: 1 }, { text: "小蜗牛回家。", start: 1.4, end: 3 }]);
assert.throws(() => boundaryCues(text, []));
assert.throws(() => boundaryCues(text, words.slice(0, 2)));
assert.throws(() => boundaryCues(text, [{ text: "无关", start: 0, end: 1 }]));
assert.throws(() => boundaryCues(text, words.map(w => ({ ...w, end: -1 }))));
const base = { title: "测试", duration: 4, characters: [], shots: [{ duration: 4, visual: "明亮温暖的小屋", characterIds: [], caption: text, asset: "a.png" }] };
assert.throws(() => validateStory({ ...base, voiceover: { provider: "edge" } }), /用户同意/);
assert.equal(validateStory({ ...base, voiceover: {} }).story.voiceover!.provider, "system");
assert.equal(validateStory({ ...base, voiceover: { provider: "edge", allowNetwork: true } }).story.voiceover!.networkRate, -10);
await assert.rejects(requireEdge("Tingting"));
const escaped = boundaryCues("A & B。", [{ text: "A", start: 0, end: .3 }, { text: "&amp;", start: .3, end: .4 }, { text: "B", start: .4, end: .8 }]);
assert.equal(escaped.map(c => c.text).join(""), "A & B。");
console.log("10 online-voice contract checks passed (no network calls)");
